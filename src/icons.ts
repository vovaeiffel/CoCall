/** Возвращает готовый <svg> для вставки в innerHTML */
export function icon(name: keyof typeof PATHS | string, size = 20): string {
    const body = PATHS[name] ?? '';
    return `<svg class="icon" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

/** Цвет аватара зависит от имени: у одного и того же человека он всегда одинаковый */
export function avatarColor(name: string): string {
    let h = 0;
    for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
    return `hsl(${h % 360}, 52%, 52%)`;
}

/** Цвет имени в тексте (чат): на светлой схеме темнее, чтобы читалось */
export function nameColor(name: string): string {
    let h = 0;
    for (let i = 0; i < name.length; i++) h = (h * 31 + name.charCodeAt(i)) >>> 0;
    const light = document.documentElement.style.colorScheme === 'light';
    return `hsl(${h % 360}, ${light ? 60 : 52}%, ${light ? 34 : 52}%)`;
}
