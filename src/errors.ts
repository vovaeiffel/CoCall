/** Не получилось начать показ экрана */
export function explainScreenError(err: unknown): string {
    const name = (err as { name?: string } | null)?.name ?? '';
    if (name === 'NotAllowedError') return t('Показ экрана отменён или не разрешён. Попробуйте ещё раз и выберите экран или окно.');
    if (name === 'NotReadableError') return t('Не получилось захватить экран: его использует другая программа. Закройте её и попробуйте снова.');
    return t('Не удалось начать показ экрана. Выберите другой экран или окно. Некоторые защищённые окна показывать нельзя.');
}

