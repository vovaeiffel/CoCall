/** Не включился микрофон */
export function explainMicError(err: unknown): FriendlyError {
    const name = (err as { name?: string } | null)?.name ?? '';
    const raw = err instanceof Error ? err.message : String(err);
    if (name === 'NotAllowedError' || name === 'SecurityError') {
        return {
            title: t('Нет доступа к микрофону'),
            text: t('Windows не разрешает CoCall пользоваться микрофоном.'),
            hints: [t('Откройте Параметры Windows → Конфиденциальность и защита → Микрофон.'), t('Включите «Доступ к микрофону» и «Разрешить классическим приложениям доступ к микрофону».'), t('Потом нажмите на значок микрофона в комнате ещё раз.')],
        };
    }
    if (name === 'NotFoundError' || name === 'OverconstrainedError') {
        return {
            title: t('Микрофон не найден'),
            text: t('Компьютер не видит ни одного микрофона.'),
            hints: [t('Подключите микрофон или гарнитуру.'), t('Проверьте, что он включён в настройках звука Windows.'), t('Выберите нужное устройство в настройках голоса (значок с ползунками в комнате).')],
        };
    }
    if (name === 'NotReadableError' || name === 'AbortError') {
        return {
            title: t('Микрофон занят'),
            text: t('Другая программа сейчас использует микрофон, и CoCall не может его получить.'),
            hints: [t('Закройте программы, которые могут слушать микрофон (Discord, Zoom, Skype, записывающие программы).'), t('Если не помогло, отключите и снова подключите микрофон.')],
        };
    }
    return { title: t('Микрофон не включился'), text: raw || t('Неизвестная ошибка микрофона.'), hints: [t('Выберите другой микрофон в настройках голоса.'), t('Перезапустите CoCall.')] };
}

