// src/lang/types.ts
export interface Language {
    /** Короткий код языка: ru, en, de… (он же показывается на кнопке) */
    code: string;
    /** Название языка на нём самом (показывается в списке выбора) */
    name: string;
    /** Локаль для времени и чисел: ru-RU, en-US, de-DE… */
    locale: string;
    /**
     * Переводы. Ключ — русская фраза так, как она написана в программе,
     * значение — перевод. Если фразы нет в списке, покажется русский текст.
     * Места для подстановок записаны так: {name}, {count} — их надо оставлять как есть.
     */
    strings: Record<string, string>;
}
